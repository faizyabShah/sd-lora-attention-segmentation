#!/usr/bin/env python3
"""Export the paper's generated tables from committed result files.

Writes ``paper/tables/generated/*.tex``. Each file starts with a header naming
its source files, their last commits and this command, which the
artifact-to-evidence audit checks (protocol Section 29). Nothing is re-run;
every number is read from a committed ``fold_results.json``.

    python scripts/paper/export_paper_artifacts.py
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CV = ROOT / "outputs" / "segmentation" / "controlled_attention_cv"
OUT = ROOT / "paper" / "tables" / "generated"
COMMAND = "python scripts/paper/export_paper_artifacts.py"


def last_commit(path: Path) -> str:
    result = subprocess.run(["git", "log", "-1", "--format=%h", "--", str(path.relative_to(ROOT))],
                            cwd=ROOT, capture_output=True, text=True, check=True)
    return result.stdout.strip() or "uncommitted"


def header(sources: list[Path]) -> str:
    lines = [f"% Generated by `{COMMAND}`; do not edit by hand.", "% Sources:"]
    lines += [f"%   {p.relative_to(ROOT)} (last commit {last_commit(p)})" for p in sources]
    return "\n".join(lines) + "\n"


def screen(path: Path, name: str) -> dict:
    return json.loads(path.read_text())["screens"][name]


def interval(s: dict) -> str:
    b = s.get("paired_bootstrap_frozen_vs_reference")
    if not b or s["frozen"] == s["reference"]:
        return "---"
    return f"${b['mean']:+.3f}$ [{b['ci_low']:+.3f}, {b['ci_high']:+.3f}]"


def controlled_path() -> None:
    """CA-C, SA-C and the joint audit: reference -> frozen choice, out of fold."""
    rows = [
        ("CA", "no 32$\\times$32 modules", CV / "ca_confirmation" / "fold_results.json", "CA-C"),
        ("SA", "module 15 only", CV / "sa_confirmation" / "fold_results.json", "SA-C"),
        ("CA$\\times$SA", "pair kept", CV / "joint_ca_sa_cartesian" / "fold_results.json", "Joint CA-SA"),
    ]
    body = []
    for stage, choice, path, name in rows:
        s = screen(path, name)
        votes = s.get("vote_winner_votes", s.get("frozen_votes"))
        body.append(f"{stage} & {choice} & {s['out_of_fold_miou_reference']:.3f} $\\to$ "
                    f"{s['out_of_fold_miou_selection']:.3f} & {votes}/5 & {interval(s)} \\\\")
    tex = (header([p for _, _, p, _ in rows])
           + "\\footnotesize\\setlength{\\tabcolsep}{2.5pt}\n"
           + "\\begin{tabular}{@{}l>{\\raggedright\\arraybackslash}p{1.4cm}ccl@{}}\n\\toprule\n"
           + "Stage & Choice & OOF mIoU & Votes & $\\Delta$ IoU [95\\% CI] \\\\\n\\midrule\n"
           + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n")
    (OUT / "controlled_path.tex").write_text(tex)


def released_baselines() -> None:
    """Registry Q1-Q5: released masks scored with OVAM's procedures, beside the frozen method."""
    base = ROOT / "outputs" / "segmentation" / "comparisons" / "released_baselines" / "summary.json"
    sa_c = CV / "sa_confirmation" / "fold_results.json"
    results = json.loads(base.read_text())["results"]
    names = {"ovam": "OVAM", "daam": "DAAM", "attn2mask": "Attn2Mask", "grounded_diffusion": "Grounded Diff.$^\\ddagger$",
             "datasetdm": "DatasetDM$^\\ddagger$"}

    def cell(dataset, method, variant):
        entry = results.get(dataset, {}).get(method, {}).get(variant)
        return f"{entry['all']['miou']:.3f}" if entry else "---"

    body = [f"{label} & {cell('voc_sim', m, 'training_free')} & {cell('voc_sim', m, 'token_optimized')} & "
            f"{cell('coco_cap', m, 'training_free')} & {cell('coco_cap', m, 'token_optimized')} \\\\"
            for m, label in names.items()]
    daam_cv = ROOT / "outputs" / "segmentation" / "comparisons" / "daam_fold_threshold" / "summary.json"
    if daam_cv.exists():
        d = json.loads(daam_cv.read_text())["variants"]
        body.insert(2, f"DAAM, threshold in our folds$^\\S$ & {d['training_free']['voc_sim']['oof_miou_fold_chosen']:.3f} & "
                       f"{d['token_optimized']['voc_sim']['oof_miou_fold_chosen']:.3f} & "
                       f"{d['training_free']['coco_cap']['miou_threshold_from_voc']:.3f} & "
                       f"{d['token_optimized']['coco_cap']['miou_threshold_from_voc']:.3f} \\\\")
    frozen = screen(sa_c, "SA-C")["out_of_fold_miou_selection"]
    tokens = CV / "tokens" / "fold_results.json"
    p3c = CV / "phase3_confirmation" / "fold_results.json"
    t_c = CV / "token_confirmation" / "fold_results.json"
    coco = ROOT / "outputs" / "segmentation" / "coco_cap_transfer" / "coco_cap" / "summary.json"
    coco_stages = json.loads(coco.read_text())["stages"] if coco.exists() else {}
    coco_t = ROOT / "outputs" / "segmentation" / "coco_cap_transfer" / "coco_cap_token" / "summary.json"
    if coco_t.exists():
        coco_stages.update(json.loads(coco_t.read_text())["stages"])

    def coco_cell(stage):
        return f"{coco_stages[stage]['miou_all']:.3f}$^\\ast$" if stage in coco_stages else "\\todo{---}"

    def oof(path, name):
        return f"{screen(path, name)['oof_miou_selection']:.3f}$^\\dagger$" if path.exists() else "\\todo{---}"

    token_ref = oof(tokens, "B1 released token, conditional query")
    body.append("\\midrule\n" + f"Ours, one SA pass & {frozen:.3f}$^\\dagger$ & {token_ref} & {coco_cell('SA/REF')} & {coco_cell('T/REF')} \\\\")
    body.append(f"Ours, final$^\\P$ & {oof(p3c, 'P3-C mandatory confirmation')} & "
                f"{oof(t_c, 'T-C mandatory confirmation (token on REF, P1, R2, P1+R2)')} & {coco_cell('P3/P1+R2')} & {coco_cell('T/R2')} \\\\")
    sources = [base, sa_c] + [x for x in (daam_cv, tokens, p3c, t_c, coco, coco_t) if x.exists()]
    tex = (header(sources)
           + "\\footnotesize\\setlength{\\tabcolsep}{3pt}\n"
           + "\\begin{tabular}{@{}lcccc@{}}\n\\toprule\n"
           + "& \\multicolumn{2}{c}{VOC-Sim} & \\multicolumn{2}{c}{COCO-Cap} \\\\\n"
           + "\\cmidrule(lr){2-3}\\cmidrule(l){4-5}\n"
           + "Method & word & token & word & token \\\\\n\\midrule\n"
           + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n")
    (OUT / "released_baselines.tex").write_text(tex)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    controlled_path()
    released_baselines()
    print(f"wrote {sorted(p.name for p in OUT.glob('*.tex'))}")


if __name__ == "__main__":
    main()
